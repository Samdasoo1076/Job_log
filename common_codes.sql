CREATE TABLE IF NOT EXISTS TBL_CODE_PARENT (
PCODE varchar(50) NOT NULL PRIMARY KEY, PCODE_MEMO longtext DEFAULT NULL,
PCODE_NM varchar(50) DEFAULT NULL, PCODE_SEQ_NO int DEFAULT NULL,
REG_DATE datetime(6) DEFAULT NULL, UP_DATE datetime(6) DEFAULT NULL, DEL_DATE datetime(6) DEFAULT NULL,
USE_TF char(1) NOT NULL DEFAULT 'Y', DEL_TF char(1) NOT NULL DEFAULT 'N'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS TBL_CODE_DETAIL (
DCODE_NO int unsigned NOT NULL AUTO_INCREMENT PRIMARY KEY,
PCODE varchar(50) NOT NULL, DCODE varchar(50) NOT NULL, DCODE_NM varchar(50) NOT NULL,
DCODE_EXT varchar(255) NOT NULL DEFAULT '', DCODE_SEQ_NO int DEFAULT NULL,
USE_TF char(1) NOT NULL DEFAULT 'Y', DEL_TF char(1) NOT NULL DEFAULT 'N',
REG_ADM int unsigned DEFAULT NULL, REG_DATE datetime DEFAULT NULL,
UP_ADM int unsigned DEFAULT NULL, UP_DATE datetime DEFAULT NULL,
DEL_ADM int unsigned DEFAULT NULL, DEL_DATE datetime DEFAULT NULL,
DCODE_INFO01 varchar(150) DEFAULT NULL, DCODE_INFO02 varchar(150) DEFAULT NULL, DCODE_INFO03 varchar(150) DEFAULT NULL,
UNIQUE KEY uq_code_detail (PCODE,DCODE),
CONSTRAINT fk_code_parent FOREIGN KEY (PCODE) REFERENCES TBL_CODE_PARENT (PCODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
